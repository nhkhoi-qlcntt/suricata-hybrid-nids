function img(path, w, h) {
  const data = fs.readFileSync(path);
  return new ImageRun({ type: "png", data, transformation: { width: w, height: h } });
}
function p(text, opts = {}) {
  return new Paragraph({
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { after: 160, line: 360 },
    children: [new TextRun({ text, font: FONT, size: 26, bold: !!opts.bold, italics: !!opts.italics, color: BLACK })],
  });
}
function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 360, after: 200 },
    children: [new TextRun({ text, font: FONT, size: 30, bold: true, color: BLACK })],
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 280, after: 160 },
    children: [new TextRun({ text, font: FONT, size: 27, bold: true, color: BLACK })],
  });
}
function caption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { after: 240 },
    children: [new TextRun({ text, font: FONT, size: 23, italics: true, color: BLACK })],
  });
}
function figure(path, w, h, capText) {
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 120, after: 80 }, children: [img(path, w, h)] }),
    caption(capText),
  ];
}
function codeBlock(lines) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: BLACK },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: BLACK },
      left: { style: BorderStyle.SINGLE, size: 4, color: BLACK },
      right: { style: BorderStyle.SINGLE, size: 4, color: BLACK },
      insideHorizontal: { style: BorderStyle.NONE, size: 0, color: BLACK },
      insideVertical: { style: BorderStyle.NONE, size: 0, color: BLACK },
    },
    rows: [new TableRow({
      children: [new TableCell({
        width: { size: 100, type: WidthType.PERCENTAGE },
        shading: { type: ShadingType.CLEAR, fill: "F2F2F2", color: "auto" },
        margins: { top: 140, bottom: 140, left: 200, right: 200 },
        children: lines.map(line => new Paragraph({
          spacing: { after: 0, line: 276 },
          children: [new TextRun({ text: line.length ? line : " ", font: "Courier New", size: 20, color: BLACK })],
        })),
      })],
    })],
  });
}
function dataTable(headers, rows, colWidths) {
  const totalW = colWidths.reduce((a, b) => a + b, 0);
  const borderAll = { style: BorderStyle.SINGLE, size: 4, color: BLACK };
  const mkCell = (text, opts = {}) => new TableCell({
    width: { size: opts.w, type: WidthType.DXA },
    shading: opts.head ? { type: ShadingType.CLEAR, fill: "D9D9D9", color: "auto" } : undefined,
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 80, bottom: 80, left: 100, right: 100 },
    children: [new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [new TextRun({ text: String(text), font: FONT, size: 21, bold: !!opts.head, color: BLACK })],
    })],
  });
  return new Table({
    width: { size: totalW, type: WidthType.DXA },
    columnWidths: colWidths,
    borders: { top: borderAll, bottom: borderAll, left: borderAll, right: borderAll, insideHorizontal: borderAll, insideVertical: borderAll },
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((hd, i) => mkCell(hd, { head: true, w: colWidths[i] })) }),
      ...rows.map(r => new TableRow({ children: r.map((c, i) => mkCell(c, { w: colWidths[i] })) })),
    ],
  });
}

